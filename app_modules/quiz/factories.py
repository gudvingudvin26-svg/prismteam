"""Фабрика для создания сущностей квиз-приложения.

Модуль предоставляет класс QuizFactory с методами для инкапсуляции
бизнес-логики создания сложных объектов: квизов, вопросов, вариантов ответов.
Использование фабрики обеспечивает:
• Единую точку валидации и нормализации входных данных;
• Автоматическое проставление связей (created_by, quiz, question);
• Централизованное логирование операций создания;
• Упрощение тестирования за счёт вынесения логики из представлений.

Типизация: используются аннотации typing для улучшения читаемости
и поддержки IDE/статических анализаторов (mypy, pyright).
"""
from typing import Dict, Any, Optional
from django.contrib.auth import get_user_model
from .models import Quiz, Question, AnswerOption
import logging

logger = logging.getLogger('quiz_log')


class QuizFactory:
    @staticmethod
    def create_quiz(data: Dict[str, Any], user) -> Quiz:
        """Создаёт новый экземпляр квиза с заданными параметрами.

        Метод инкапсулирует логику создания объекта Quiz:
        1. Извлекает и нормализует поля из входного словаря data:
           • title (обязательное) — название квиза;
           • description (опциональное, по умолчанию '') — описание;
           • timer (опциональное) — ограничение времени в секундах;
           • points_per_question (опциональное, по умолчанию 100) — баллы за ответ.
        2. Привязывает квиз к пользователю-создателю через параметр user.
        3. Сохраняет объект в базу данных через ORM Django.
        4. Логирует успешное создание с указанием ID квиза и имени пользователя.

        Примечания:
        • Валидация данных (например, минимальная длина title) должна
          выполняться на уровне сериализатора или формы до вызова фабрики.
        • Метод не создаёт вопросы и варианты ответов — это ответственность
          вызывающего кода или отдельных фабричных методов (при расширении).

        Args:
            data (Dict[str, Any]): Словарь с параметрами квиза.
                Ожидаемые ключи: 'title', 'description', 'timer', 'points_per_question'.
            user: Экземпляр модели User, создающий квиз (для поля created_by).

        Returns:
            Quiz: Сохранённый экземпляр модели Quiz с присвоенным первичным ключом.

        Raises:
            IntegrityError: При нарушении ограничений БД (уникальность, NOT NULL).
            ValidationError: Если входные данные не прошли валидацию на уровне модели.

        Side effects:
            • Запись в базу данных (INSERT в таблицу quiz_quiz).
            • Запись в лог 'quiz_log' уровня INFO с данными о создании.
        """
        quiz_data = {
            'title': data.get('title'),
            'description': data.get('description'),
            'timer': data.get('timer'),
            'points_per_question': data.get('points_per_question', 100),
            'created_by': user,
        }

        quiz = Quiz.objects.create(**quiz_data)

        return quiz