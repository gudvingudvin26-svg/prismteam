"""Фильтры для настройки логирования приложения.

Модуль предоставляет кастомные фильтры для модуля logging Django/Python:
• InfoOrErrorFilter — пропускает только записи уровней INFO, ERROR и CRITICAL,
  отсекая DEBUG и WARNING для снижения шума в продакшн-логах.
• UserContextFilter — обогащает лог-записи контекстными полями (user_id, quiz_id, session_id),
  устанавливая значения по умолчанию для анонимных запросов.

Фильтры применяются в конфигурации логгеров через settings.py для гибкого
управления выводом логов в разные хэндлеры (консоль, файл, внешние системы).
"""
import logging


class InfoOrErrorFilter(logging.Filter):
    """Фильтр для выборочного пропуска лог-записей по уровню важности.

    Предназначен для использования в хэндлерах, куда следует выводить
    только значимые события: информационные сообщения (INFO), ошибки (ERROR)
    и критические сбои (CRITICAL). Записи уровней DEBUG и WARNING
    автоматически отфильтровываются, что снижает объём логов в продакшене
    и упрощает мониторинг инцидентов.

    Наследуется от logging.Filter, переопределяет метод filter() для
    реализации кастомной логики отбора записей.

    Пример использования в settings.py:
        'filters': {
            'info_or_error': {
                '()': 'app_modules.quiz.logging_utils.InfoOrErrorFilter',
            },
        },
        'handlers': {
            'console': {
                'filters': ['info_or_error'],
                ...
            },
        },
    """

    def filter(self, record):
        """Определяет, должна ли лог-запись быть обработана хэндлером.

        Метод вызывается для каждой записи лога перед её выводом.
        Возвращает True, если уровень записи равен INFO, ERROR или CRITICAL.
        Возвращает False для всех остальных уровней (DEBUG, WARNING и др.),
        что приводит к игнорированию записи данным хэндлером.

        Args:
            record: Экземпляр logging.LogRecord с данными события.

        Returns:
            bool: True если запись должна быть выведена, False если отфильтрована.
        """
        return record.levelno == logging.INFO or record.levelno == logging.ERROR or record.levelno == logging.CRITICAL


class UserContextFilter(logging.Filter):
    """Фильтр для добавления контекстной информации в лог-записи.

    Предназначен для обогащения логов идентификаторами сущностей приложения:
    • user_id — идентификатор пользователя, совершившего действие;
    • quiz_id — идентификатор квиза, с которым связана операция;
    • session_id — идентификатор сессии (для отслеживания цепочек запросов).

    Если поля не переданы через extra={} при вызове logger.info()/error(),
    фильтр автоматически устанавливает значения по умолчанию:
    'anonymous' для user_id и 'none' для quiz_id/session_id.
    Это гарантирует наличие контекстных полей во всех записях, что упрощает
    фильтрацию и агрегацию логов в системах мониторинга (ELK, Splunk, Grafana).

    Возвращает True для всех записей, не отфильтровывая их, а только модифицируя.

    Пример использования:
        logger.info("Действие выполнено", extra={'user_id': 123, 'quiz_id': 456})
        # В логе появится: {..., "user_id": 123, "quiz_id": 456, "session_id": "none"}

        logger.error("Ошибка валидации")  # без extra
        # В логе появится: {..., "user_id": "anonymous", "quiz_id": "none", "session_id": "none"}
    """

    def filter(self, record):
        """Добавляет контекстные поля в лог-запись или устанавливает значения по умолчанию.

        Метод проверяет наличие атрибутов user_id, quiz_id, session_id в объекте record.
        Если атрибут отсутствует — создаёт его со значением по умолчанию:
        • user_id → 'anonymous' (для неаутентифицированных запросов);
        • quiz_id → 'none' (если операция не связана с конкретным квизом);
        • session_id → 'none' (если сессия не отслеживается).

        После обогащения записи возвращает True, разрешая её дальнейшую обработку.

        Args:
            record: Экземпляр logging.LogRecord, который будет модифицирован.

        Returns:
            bool: Всегда True, так как фильтр не отбрасывает записи, а только дополняет их.
        """
        if not hasattr(record, 'user_id'):
            record.user_id = 'anonymous'
        if not hasattr(record, 'quiz_id'):
            record.quiz_id = 'none'
        if not hasattr(record, 'session_id'):
            record.session_id = 'none'
        return True