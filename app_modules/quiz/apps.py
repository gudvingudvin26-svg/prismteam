"""Конфигурация Django-приложения квизов.

Модуль содержит класс QuizConfig, наследующий AppConfig, для настройки
метаданных и инициализации приложения app_modules.quiz. Используется
Django для регистрации приложения, управления миграциями и подключения
сигналов при старте проекта.
"""
from django.apps import AppConfig


class QuizConfig(AppConfig):
    """Конфигурация приложения квизов: метаданные и точка входа для инициализации.

    Атрибуты:
        default_auto_field (str): Тип поля по умолчанию для автоинкрементных
            первичных ключей. Используется BigAutoField для поддержки больших
            объёмов данных (до 9 223 372 036 854 775 807 записей).
        name (str): Полный путь к модулю приложения в проекте. Указывает Django,
            где искать модели, сигналы и другие компоненты приложения.

    Примечания:
        • Класс автоматически обнаруживается Django при наличии в INSTALLED_APPS.
        • Для выполнения кода при старте приложения переопределите метод ready().
        • Значение default_auto_field можно изменить на 'django.db.models.AutoField'
          для совместимости со старыми миграциями, но BigAutoField рекомендуется
          для новых проектов.

    Пример использования в settings.py:
        INSTALLED_APPS = [
            ...
            'app_modules.quiz',  # Django автоматически найдёт QuizConfig
        ]
    """
    default_auto_field = 'django.db.models.BigAutoField'
    name = 'app_modules.quiz'